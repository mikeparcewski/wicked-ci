"""wicked-crew vitest tests (`packages/crew/tests/**.test.ts`, optionally one named test).

The file runs under crew's OWN vitest config (its hermetic-home setup files included); the runner
writes a config next to it that only appends taps/vitest-tap.mjs to `setupFiles`, so every Fastify
`inject()` and /api/ `fetch` the test drives is recorded as the API transcript. The vitest JSON
report is kept as the test report. Integration fidelity: never a pass (verdict.py).
"""
import json
import os
import re

from . import DOUBLED, Adapter, Outcome, read_jsonl, run_logged, write_json

TEST_RE = re.compile(r"^packages/(crew|crew-api-types)/(tests/.+\.test\.(ts|mts|js|mjs))$")

CONFIG = """// generated by wicked-ci e2e (the certification runner): crew's own config + the HTTP tap.
import base from './vitest.config.ts';
import { mergeConfig } from 'vitest/config';
export default mergeConfig(base, { test: { setupFiles: [%s] } });
"""


class VitestAdapter(Adapter):
    name = "wicked-crew-vitest"
    targets = ("fixture",)

    def claim(self, scenario, ctx):
        repo, _, path = scenario["ref"].partition(":")
        m = TEST_RE.match(path)
        if repo != "wicked-crew" or not m or ctx.target not in self.targets:
            return None
        return "wicked-crew-vitest:" + path, {"pkg": m.group(1), "file": m.group(2), "name": scenario.get("name")}

    def available(self, ctx, params):
        crew = ctx.checkouts.get("wicked-crew")
        if not crew:
            return "checkout:wicked-crew", "pass --src DIR or --checkout wicked-crew=PATH"
        pkg = os.path.join(crew, "packages", params["pkg"])
        if not os.path.isfile(os.path.join(pkg, params["file"])):
            return "checkout:wicked-crew", "%s is not in this checkout" % params["file"]
        if not any(os.path.isfile(os.path.join(d, "node_modules", ".bin", "vitest")) for d in (crew, pkg)):
            return "checkout:wicked-crew", "no node_modules: run `npm ci` in the checkout"
        return None

    def provides(self, ctx, scenario):
        return {k: "the test's in-process daemon and doubles" for k in DOUBLED}

    def evidence_kinds(self, ctx, scenario, cap):
        return {"api-transcript", "event-log", "test-report"}

    def run(self, unit, ctx):
        crew = ctx.checkouts["wicked-crew"]
        any_s = next(iter(unit.scenarios.values()))
        pkg_dir = os.path.join(crew, "packages", any_s["params"]["pkg"])
        out = os.path.join(ctx.run_dir, "scenarios", unit.slug)
        os.makedirs(out, exist_ok=True)
        tap_file = os.path.join(out, "http-tap.jsonl")
        cfg = os.path.join(pkg_dir, ".e2e-vitest.config.mts")
        with open(cfg, "w", encoding="utf-8") as fh:
            fh.write(CONFIG % json.dumps(os.path.join(ctx.taps_dir, "vitest-tap.mjs").replace(os.sep, "/")))
        names = {s["params"]["name"] for s in unit.scenarios.values()}
        report = os.path.join(out, "vitest-report.json")
        argv = ctx.build_slot + [ctx.npx, "vitest", "run", "--config", cfg, any_s["params"]["file"],
                                 "--reporter=default", "--reporter=json", "--outputFile=" + report]
        if len(names) == 1 and None not in names:
            argv += ["-t", re.escape(next(iter(names)))]
        env = dict(os.environ, E2E_HTTP_TAP=tap_file, CI="1")
        try:
            rc, secs = run_logged(argv, pkg_dir, env, os.path.join(out, "vitest.log"), ctx.unit_timeout)
        finally:
            try:
                os.remove(cfg)
            except OSError:
                pass
        tests = []
        if os.path.isfile(report):
            with open(report, encoding="utf-8") as fh:
                rep = json.load(fh)
            for f in rep.get("testResults", []):
                tests += [{"name": a.get("fullName") or a.get("title"), "title": a.get("title"),
                           "status": a.get("status")} for a in f.get("assertionResults", [])]
        taps = read_jsonl(tap_file)
        outcomes = {}
        for key, s in unit.scenarios.items():
            name = s["params"]["name"]
            if not tests:
                o = Outcome("error", "vitest produced no report (exit %s; see vitest.log)" % rc, s.get("fidelity"))
            elif name:
                mine = [t for t in tests if t["title"] == name or (t["name"] or "").endswith(name)] or \
                       [t for t in tests if name in (t["name"] or "")]
                if not mine:
                    o = Outcome("error", "no test named %r in %s" % (name, s["params"]["file"]), s.get("fidelity"))
                elif any(t["status"] == "failed" for t in mine):
                    o = Outcome("failed", "failed: %s" % "; ".join(t["name"] for t in mine if t["status"] == "failed"), s.get("fidelity"))
                elif all(t["status"] in ("skipped", "pending", "todo") for t in mine):
                    o = Outcome("error", "the named test was skipped", s.get("fidelity"))
                elif rc is None:
                    o = Outcome("error", "vitest timed out (the unit ceiling)", s.get("fidelity"))
                elif rc != 0:
                    o = Outcome("failed", "the named test passed but vitest exited %s (a hook or teardown failed)" % rc, s.get("fidelity"))
                else:
                    o = Outcome("passed", "%d test(s) passed" % sum(t["status"] == "passed" for t in mine), s.get("fidelity"))
            else:
                failed = [t["name"] for t in tests if t["status"] == "failed"]
                ran = [t for t in tests if t["status"] == "passed"]
                if rc is None:
                    o = Outcome("error", "vitest timed out (the unit ceiling)", s.get("fidelity"))
                else:
                    o = Outcome("failed" if failed or rc != 0 else ("passed" if ran else "error"),
                                ("failed: " + "; ".join(failed[:5])) if failed else "%d tests passed (exit %s)" % (len(ran), rc),
                                s.get("fidelity"))
            o.add("test-report", report)
            o.add("test-report", os.path.join(out, "vitest.log"))
            mine_taps = [t for t in taps if not name or name in (t.get("test") or "")] or ([] if name else taps)
            for t in mine_taps:
                o.obs.add_http(t.get("method"), t.get("url"), t.get("status"), t.get("req"), t.get("res"),
                               source="vitest-" + str(t.get("via")))
            o.obs.events_from_http()
            if o.obs.http:
                o.add("api-transcript", write_json(os.path.join(out, _slug(key) + "-api-transcript.json"), o.obs.http))
            if o.obs.events:
                o.add("event-log", write_json(os.path.join(out, _slug(key) + "-event-log.json"), o.obs.events))
            o.extra = {"tests": [t for t in tests if not name or name in (t["name"] or "")][:50]}
            outcomes[key] = o
        return outcomes


def _slug(s):
    return re.sub(r"[^\w.-]+", "_", s)[-80:]

