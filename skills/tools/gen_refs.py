#!/usr/bin/env python3
"""Generate the per-area references of the wicked-e2e skill from the catalog (stdlib only).

    python3 skills/tools/gen_refs.py           # rewrite the generated block of every refs/<area>.md
    python3 skills/tools/gen_refs.py --check   # CI: fail when a ref is missing, stale or incomplete

Each `skills/wicked-e2e/refs/<area>.md` has two parts:

- a hand-written `## Setup quirks` section (kept as written: what the catalog cannot say), and
- a generated block between the BEGIN/END markers: the area's counts, its tags, its dependency
  classes (deps.py's rule table) and which adapters can run its scenarios. Regenerated from
  `e2e/catalog/<area>.json`, so it cannot drift.

`--check` fails when an area has no ref, a ref names no area, a quirks section is empty, a generated
block differs from what the catalog gives, a catalog tag is listed in no ref, or the router's
SKILL.md does not link every ref.
"""
import os
import sys
import types

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(ROOT, "e2e", "lib"))

from e2ecat import deps as depsmod  # noqa: E402
from e2ecat import validate as v  # noqa: E402
from e2ecat.adapters import all_adapters  # noqa: E402
from e2ecat.select import select  # noqa: E402

REFS = os.path.join(ROOT, "skills", "wicked-e2e", "refs")
ROUTER = os.path.join(ROOT, "skills", "wicked-e2e", "SKILL.md")
BEGIN = "<!-- BEGIN generated by skills/tools/gen_refs.py from e2e/catalog: do not edit by hand -->"
END = "<!-- END generated -->"


def _runnable(cap, target):
    ctx = types.SimpleNamespace(target=target, checkouts={})
    for s in cap.get("scenarios", []):
        if isinstance(s, dict) and any(ad.claim(s, ctx) for ad in all_adapters()):
            return True
    return False


def _fmt(counts):
    return ", ".join("%s %d" % kv for kv in sorted(counts.items(), key=lambda kv: (-kv[1], kv[0])))


def _inc(d, k):
    d[k] = d.get(k, 0) + 1


def generated(area, doc, caps, catalog_ids):
    cost, surf, okind, fid, tags, groups, classes, examples = {}, {}, {}, {}, {}, {}, {}, {}
    run = {"fixture adapter": 0, "live journey": 0, "planned only": 0, "no adapter yet": 0}
    for c in caps:
        _inc(cost, c["cost"])
        _inc(surf, c["surface"])
        o = c["oracle"]
        _inc(okind, "manual" if o["kind"] == "manual" else ("complete" if v.oracle_complete(o) else "partial"))
        _inc(fid, v.best_fidelity(c) or "planned")
        for t in c["tags"]:
            _inc(tags, t)
        parts = c["id"].split(".")
        _inc(groups, ".".join(parts[:2]) if len(parts) > 1 else c["id"])  # root.group: an area can hold several roots
        mine = set()
        for d in c.get("deps", []):
            k = depsmod.classify(d, catalog_ids)
            if k not in mine:  # count a class once per capability; collect every example
                mine.add(k)
                _inc(classes, k)
            ex = examples.setdefault(k, [])
            if d not in ex and len(ex) < 3:
                ex.append(d)
        real = [s for s in c.get("scenarios", []) if isinstance(s, dict)]
        if not real:
            run["planned only"] += 1
        elif _runnable(c, "fixture"):
            run["fixture adapter"] += 1
        elif _runnable(c, "live"):
            run["live journey"] += 1
        else:
            run["no adapter yet"] += 1
    L = [BEGIN, "", "## From the catalog", "", "%s" % doc.get("description", "").strip(), "",
         "| | |", "|---|---|",
         "| capabilities | %d |" % len(caps),
         "| cost | %s |" % _fmt(cost),
         "| surface | %s |" % _fmt(surf),
         "| oracle | %s |" % _fmt(okind),
         "| best scenario fidelity | %s |" % _fmt(fid),
         "| who can run it | %s |" % _fmt({k: n for k, n in run.items() if n}),
         "", "Select it: `area:%s`; the cheap part: `area:%s cost<=S`; one group: `id:<group>,<group>.*` with a "
             "group below (e.g. `id:%s,%s.*`)." % (area, area, sorted(groups)[0] if groups else area,
                                                   sorted(groups)[0] if groups else area),
         "", "### Tags", "", ", ".join("`%s` %d" % (t, n) for t, n in sorted(tags.items())), "",
         "### Id groups", "", "Each count is what `id:<group>,<group>.*` selects (aliases included).", "",
         ", ".join("`%s` %d" % (g, len(select(caps, "id:%s,%s.*" % (g, g)))) for g in sorted(groups)), "",
         "### Dependencies (requirement classes)", "",
         "| class | capabilities | e.g. |", "|---|---:|---|"]
    for k, n in sorted(classes.items(), key=lambda kv: (-kv[1], kv[0])):
        L.append("| %s | %d | %s |" % (k, n, "; ".join(x.replace("|", "/") for x in examples[k])))
    L += ["", "\"who can run it\": `fixture adapter` = a scenario an adapter runs on the fixture target (given the checkouts it needs); `live journey` = only "
          "an e2e-live studio journey (`--target live --live-journeys`); `no adapter yet` = no adapter runs its catalog "
          "scenarios; `planned only` = it has no scenario yet. This is catalog-scenario coverage: on the live target the "
          "runner's own direct reads may still prove a read-only capability, and `--plan-only` gives the actual "
          "assignment.", "", END, ""]
    return "\n".join(L)


def load():
    _, docs, caps = v.load_catalog(os.path.join(ROOT, "e2e"))
    ids = frozenset(c["id"] for c in caps) | frozenset(a for c in caps for a in c.get("aliases", []))
    by_area = {}
    for c in caps:
        by_area.setdefault(c["_area"], []).append(c)
    return docs, by_area, ids, caps


def split(text):
    if BEGIN in text and END in text:
        head, rest = text.split(BEGIN, 1)
        return head, rest.split(END, 1)[1]
    return text, ""


def main(argv):
    check = "--check" in argv
    docs, by_area, ids, caps = load()
    fails = []
    listed_tags = set()
    for area in v.AREAS:
        p = os.path.join(REFS, area + ".md")
        gen = generated(area, docs.get(area, {}), by_area.get(area, []), ids)
        listed_tags |= {t for c in by_area.get(area, []) for t in c["tags"]} if gen else set()
        if not os.path.isfile(p):
            fails.append("refs/%s.md is missing (every catalog area needs a ref)" % area)
            if not check:
                with open(p, "w", encoding="utf-8", newline="\n") as fh:
                    fh.write("# %s\n\n## Setup quirks\n\n(write them)\n\n%s" % (area, gen))
            continue
        with open(p, encoding="utf-8") as fh:
            text = fh.read()
        head, tail = split(text)
        quirks = head.split("## Setup quirks", 1)[1].strip() if "## Setup quirks" in head else ""
        if not quirks or quirks.startswith("(write them)"):
            fails.append("refs/%s.md: the hand-written `## Setup quirks` section is empty" % area)
        new = head.rstrip() + "\n\n" + gen + tail.lstrip("\n")
        if new != text:
            if check:
                fails.append("refs/%s.md: the generated block is stale; run python3 skills/tools/gen_refs.py" % area)
            else:
                with open(p, "w", encoding="utf-8", newline="\n") as fh:
                    fh.write(new)
        elif check:
            for t in {t for c in by_area.get(area, []) for t in c["tags"]}:
                if "`%s` " % t not in text:
                    fails.append("refs/%s.md does not list tag %s" % (area, t))
    for f in sorted(os.listdir(REFS)):
        if f.endswith(".md") and f[:-3] not in v.AREAS:
            fails.append("refs/%s names no catalog area" % f)
    # Every documented group selector selects exactly its advertised count.
    for area, acaps in by_area.items():
        groups = {}
        for c in acaps:
            parts = c["id"].split(".")
            g = ".".join(parts[:2]) if len(parts) > 1 else c["id"]
            groups[g] = groups.get(g, 0) + 1
        covered = set()
        for g in groups:
            got = {c["id"] for c in select(acaps, "id:%s,%s.*" % (g, g))}
            if not got:
                fails.append("refs/%s.md: group selector id:%s,%s.* selects nothing" % (area, g, g))
            covered |= got
        if covered != {c["id"] for c in acaps}:
            fails.append("refs/%s.md: the group selectors miss %s" % (area, sorted({c["id"] for c in acaps} - covered)[:3]))
    all_tags = {t for c in caps for t in c["tags"]}
    for t in sorted(all_tags - listed_tags):
        fails.append("tag %s is listed in no ref" % t)
    with open(ROUTER, encoding="utf-8") as fh:
        router = fh.read()
    for area in v.AREAS:
        if "refs/%s.md" % area not in router:
            fails.append("wicked-e2e/SKILL.md does not link refs/%s.md" % area)
    for f in fails:
        print("gen_refs: %s" % f, file=sys.stderr)
    if check:
        print("gen_refs --check: %d areas, %d tags; %s" % (len(v.AREAS), len(all_tags), "OK" if not fails else "%d FAILURES" % len(fails)))
        return 1 if fails else 0
    print("gen_refs: wrote %d refs" % len(v.AREAS))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
